/**
 * Абстракция базы данных.
 *
 * Зачем интерфейс: продакшен работает на PostgreSQL (драйвер `pg`), а локальная
 * разработка и автотесты — на PGlite (тот же PostgreSQL, собранный в WebAssembly).
 * SQL в обоих случаях ОДИН И ТОТ ЖЕ, поэтому поведение совпадает, а для запуска
 * проекта не нужен установленный сервер базы.
 *
 * Все запросы параметризованы ($1, $2, …) — склейка значений в строку запрещена.
 */

/** Результат запроса: массив строк с типизированными полями. */
export type QueryRow = Record<string, unknown>;

export interface Database {
  /**
   * Выполнить запрос и получить строки.
   *
   * Тип строки задаёт вызывающий (`query<UserRow>(...)`). Ограничения на форму
   * типа нет — так же устроена типизация драйвера `pg`: имена и типы колонок
   * известны из SQL, который пишет репозиторий.
   */
  query<Row = QueryRow>(sql: string, params?: readonly unknown[]): Promise<Row[]>;

  /** Выполнить запрос, результат которого не нужен. */
  execute(sql: string, params?: readonly unknown[]): Promise<void>;

  /**
   * Выполнить набор операций в транзакции: либо всё, либо ничего.
   * Обязателен для операций, которые меняют несколько таблиц сразу
   * (передача производству, возврат из архива, импорт спецификации).
   */
  transaction<T>(fn: (tx: Database) => Promise<T>): Promise<T>;

  /** Закрыть соединение (используется при остановке сервера и в тестах). */
  close(): Promise<void>;
}

